export function translateQuestion(question, locale) {
  if (locale !== 'en' || !question) return question;
  return {
    ...question,
    label: QUESTION_LABEL_EN[question.label] || question.label,
    help: question.help ? (HELP_EN[question.help] || question.help) : question.help,
    moduleName: question.moduleName ? (MODULE_NAME_EN[question.moduleName] || question.moduleName) : question.moduleName,
    options: Array.isArray(question.options)
      ? question.options.map((option) => ({ ...option, label: OPTION_LABEL_EN[option.label] || option.label }))
      : question.options,
    config: question.config
      ? {
          ...question.config,
          labels: Array.isArray(question.config.labels)
            ? question.config.labels.map((label) => OPTION_LABEL_EN[label] || label)
            : question.config.labels
        }
      : question.config
  };
}

export function translateModuleName(name, locale) {
  return locale === 'en' ? (MODULE_NAME_EN[name] || name) : name;
}
